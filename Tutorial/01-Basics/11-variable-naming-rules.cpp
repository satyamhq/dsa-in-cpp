// Variable naming rules in C++
//
// 1. A variable name can contain letters, digits, and underscore (_).
//    Example: int studentMarks;
//
// 2. A variable name cannot start with a digit.
//    Correct: int marks1;
//    Incorrect: int 1marks;
//
// 3. A variable name cannot contain spaces.
//    Correct: int studentMarks;
//    Incorrect: int student marks;
//
// 4. A variable name cannot use special characters such as @, #, $, %, etc.
//    Correct: int totalMarks;
//    Incorrect: int total@Marks;
//
// 5. C++ is case-sensitive.
//    Example: age, Age, and AGE are different variables.
//
// 6. C++ keywords cannot be used as variable names.
//    Example: int, float, class, return, if, while, etc.
//
// 7. Variable names should be meaningful and descriptive.
//    Good: int studentAge;
//    Bad: int x;
//
// 8. Use camelCase or snake_case consistently.
//    Example: int studentAge;
//    Example: int student_age;
//
// 9. Variable names can start with an underscore, but avoid names
//    beginning with an underscore followed by a capital letter,
//    as some such names are reserved by C++.
//
// 10. There is no fixed limit on the length of a variable name,
//     but keep names readable and meaningful.